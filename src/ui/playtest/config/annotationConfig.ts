export const DEFAULT_ANNOTATION_ASSISTANT_CONFIG: AnnotationAssistantConfig =
  AnnotationAssistantConfigSchema.parse(defaultConfigInput);

/**
 * Merge helper guaranteeing defaults for optional consumer overrides.
 */
export function mergeAnnotationConfig(
  overrides?: Partial<AnnotationAssistantConfig>,
): AnnotationAssistantConfig {
  if (!overrides) {
    return DEFAULT_ANNOTATION_ASSISTANT_CONFIG;
  }

  return {
    ...DEFAULT_ANNOTATION_ASSISTANT_CONFIG,
    ...overrides,
    tags: overrides.tags ?? DEFAULT_ANNOTATION_ASSISTANT_CONFIG.tags,
    quickNotes: overrides.quickNotes ?? DEFAULT_ANNOTATION_ASSISTANT_CONFIG.quickNotes,
    severities: {
      ...DEFAULT_ANNOTATION_ASSISTANT_CONFIG.severities,
      ...(overrides.severities ?? {}),
    },
    timeline: {
      ...DEFAULT_ANNOTATION_ASSISTANT_CONFIG.timeline,
      ...(overrides.timeline ?? {}),
    },
    markdown: {
      ...DEFAULT_ANNOTATION_ASSISTANT_CONFIG.markdown,
      ...(overrides.markdown ?? {}),
    },
    eventTaggingRules: {
      ...DEFAULT_ANNOTATION_ASSISTANT_CONFIG.eventTaggingRules,
      ...(overrides.eventTaggingRules ?? {}),
    },
  };
}
