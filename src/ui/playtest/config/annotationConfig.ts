import { z } from 'zod';
import { PlaytestEventTypeSchema, type PlaytestEventType } from './playtestConfig';

/**
 * Annotation severity levels available to the assistant UI.
 */
export const AnnotationSeveritySchema = z.enum(['info', 'issue', 'blocker']);

export type AnnotationSeverity = z.infer<typeof AnnotationSeveritySchema>;

/**
 * Annotation tag definition used for quick tagging controls.
 */
export const AnnotationTagSchema = z.object({
  id: z.string(),
  label: z.string(),
  color: z.string().default('#94a3b8'),
  icon: z.string().optional(),
  shortcut: z.string().optional(),
  description: z.string().optional(),
});

export type AnnotationTag = z.infer<typeof AnnotationTagSchema>;

/**
 * Quick note chip definition, optionally preloading tags.
 */
export const QuickNoteSchema = z.object({
  id: z.string(),
  label: z.string(),
  template: z.string(),
  tags: z.array(z.string()).default([]),
});

export type QuickNoteTemplate = z.infer<typeof QuickNoteSchema>;

const TimelineSettingsSchema = z.object({
  refreshIntervalMs: z.number().min(250).max(5000).default(1000),
  maxVisibleEvents: z.number().min(5).max(200).default(80),
  markerSizePx: z.number().min(4).max(18).default(8),
  showEventTypeLegend: z.boolean().default(true),
});

const MarkdownSettingsSchema = z.object({
  headingLevel: z.number().min(1).max(6).default(3),
  includeSummary: z.boolean().default(true),
  includeTimeline: z.boolean().default(true),
  includeDeviceInfo: z.boolean().default(true),
  includePerformance: z.boolean().default(false),
  footnote: z.string().optional(),
});

const SeverityStyleSchema = z.object({
  label: z.string(),
  color: z.string(),
  accent: z.string(),
});

const SeverityRecordSchema = z.record(AnnotationSeveritySchema, SeverityStyleSchema);

const eventTaggingShape = PlaytestEventTypeSchema.options.reduce(
  (shape, eventType) => {
    shape[eventType] = z.array(z.string()).optional();
    return shape;
  },
  {} as Record<PlaytestEventType, z.ZodOptional<z.ZodArray<z.ZodString>>>,
);

const EventTaggingRulesSchema = z
  .object(eventTaggingShape)
  .partial()
  .transform((value) => value as Partial<Record<PlaytestEventType, string[]>>)
  .default({});

export type SeverityStyle = z.infer<typeof SeverityStyleSchema>;

export interface AnnotationAssistantConfig {
  tags: AnnotationTag[];
  quickNotes: QuickNoteTemplate[];
  severities: Record<AnnotationSeverity, SeverityStyle>;
  timeline: z.infer<typeof TimelineSettingsSchema>;
  markdown: z.infer<typeof MarkdownSettingsSchema>;
  eventTaggingRules: Partial<Record<PlaytestEventType, string[]>>;
}

export const AnnotationAssistantConfigSchema = z.object({
  tags: z.array(AnnotationTagSchema),
  quickNotes: z.array(QuickNoteSchema),
  severities: SeverityRecordSchema,
  timeline: TimelineSettingsSchema,
  markdown: MarkdownSettingsSchema,
  eventTaggingRules: EventTaggingRulesSchema,
});

