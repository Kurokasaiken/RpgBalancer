/**
 * Hero level-up presentation events (PLAN-032 SP-5, artifact r009).
 *
 * A typed in-page bus for the staging presentation beat. The payload implies
 * no XP gain, persistence, or mutation — it only asks the rosterV2 decorative
 * layer to flash a badge/ring/floater for a resident.
 *
 * `useHeroLevelUp` is the seam PROGRESSION.md wiring will call to dispatch the
 * SAME presentation event when the real system lands. It owns no progression
 * semantics today and is never claimed as settlement integration; the mock
 * event type stays explicitly staging-specific.
 */

/** Typed presentation event; `eventId` is monotonic — newer wins every supersede rule. */
export interface HeroLevelUpEvent {
  type: 'hero_levelup_mock';
  residentId: string;
  level: number;
  /** `<commandSeq>:<targetIndex>` — generated by the command handler, not here. */
  eventId: string;
}

type HeroLevelUpListener = (event: HeroLevelUpEvent) => void;

const listeners = new Set<HeroLevelUpListener>();

/** Subscribe to level-up presentation events; returns the unsubscribe callback. */
export const subscribeHeroLevelUp = (listener: HeroLevelUpListener): (() => void) => {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
};

/**
 * Dispatches a presentation event to every subscriber. `eventId` must come
 * from the caller (the command handler owns the monotonic counter).
 */
export const dispatchHeroLevelUp = (event: HeroLevelUpEvent): void => {
  listeners.forEach((listener) => listener(event));
};

/**
 * Typed contract stub (artifact r009): the name future settlement wiring will
 * call to dispatch the SAME presentation event. Returns the dispatcher; it
 * owns no progression semantics today, is not a partial progression API, and
 * is never claimed as implemented settlement integration.
 */
export const useHeroLevelUp = (): ((event: HeroLevelUpEvent) => void) => dispatchHeroLevelUp;
