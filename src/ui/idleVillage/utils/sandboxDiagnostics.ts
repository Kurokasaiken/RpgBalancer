/**
 * Global store for diagnostic logs, accessible by the diagnostics panel.
 */
const diagnosticLogs: DiagnosticLog[] = [];
const perChannelLogs: Partial<Record<string, DiagnosticLog[]>> = {};
const listeners = new Set<() => void>();
let registeredChannels: ChannelRegistry = { ...defaultChannels };

const notifyListeners = () => {
  listeners.forEach((listener) => {
    try {
      listener();
    } catch (error) {
      console.warn('[IdleVillageDiagnostics] listener error', error);
    }
  });
};

export const configureDiagnosticsChannels = (registry: ChannelRegistry): void => {
  registeredChannels = { ...registry };
  const registeredIds = Object.keys(registeredChannels);
  registeredIds.forEach((id) => {
    if (!perChannelLogs[id]) {
      perChannelLogs[id] = [];
    }
  });
};

// Ensure default channels have buffers
configureDiagnosticsChannels(defaultChannels);

export const getDiagnosticsChannelRegistry = (): ChannelRegistry => registeredChannels;

export const subscribeToDiagnostics = (listener: () => void): (() => void) => {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
};

/**
 * Adds a log entry to the global store if diagnostics are enabled.
 */
const recordLog = (log: DiagnosticLog): void => {
  if (!isDiagnosticsEnabled()) {
    return;
  }

  const channelDef =
    registeredChannels[log.channel] ??
    (registeredChannels[log.channel] = {
      id: log.channel,
      label: log.channel,
      description: `Diagnostics channel ${log.channel}`,
      bufferSize: 400,
    });
  const normalizedLog = channelDef?.formatter ? channelDef.formatter(log) : log;

  diagnosticLogs.push(normalizedLog);
  if (diagnosticLogs.length > 1000) {
    diagnosticLogs.splice(0, diagnosticLogs.length - 1000);
  }

  const channelBuffer = perChannelLogs[log.channel] ?? (perChannelLogs[log.channel] = []);
  channelBuffer.push(normalizedLog);
  const bufferSize = channelDef?.bufferSize ?? 400;
  if (channelBuffer.length > bufferSize) {
    channelBuffer.splice(0, channelBuffer.length - bufferSize);
  }

  notifyListeners();
};

/**
 * Gets filtered logs by channel and optional timestamp range.
 */
export const getDiagnosticLogs = (
  filter?: { channel?: DiagnosticsChannelId; since?: number; tags?: string[] },
): DiagnosticLog[] => {
  let logs = diagnosticLogs;
  const { channel, tags } = filter ?? {};
  const since = filter?.since;

  if (channel) {
    logs = logs.filter((log) => log.channel === channel);
  }
  if (typeof since === 'number') {
    logs = logs.filter((log) => log.timestamp >= since);
  }
  if (tags && tags.length > 0) {
    logs = logs.filter(
      (log) => log.tags?.some((tag) => tags.includes(tag)) ?? false,
    );
  }
  return [...logs];
};

/**
 * Exports all logs as JSON string.
 */
export const exportDiagnosticLogs = (): string => {
  return JSON.stringify(
    {
      exportedAt: new Date().toISOString(),
      channelRegistry: registeredChannels,
      logs: diagnosticLogs,
    },
    null,
    2,
  );
};

/**
 * Clears all diagnostic logs.
 */
export const clearDiagnosticLogs = (): void => {
  diagnosticLogs.length = 0;
  Object.values(perChannelLogs).forEach((buffer) => {
    if (buffer) {
      buffer.length = 0;
    }
  });
  notifyListeners();
};

/**
 * Determines whether diagnostics should emit to the console.
 */
interface IdleVillageDiagnosticsEnv {
  VITE_IDLE_VILLAGE_DIAGNOSTICS?: string;
  VITE_ENABLE_SANDBOX_DIAGNOSTICS?: string;
}

export const isSandboxDiagnosticsRuntimeEnabled = (): boolean => {
  if (typeof window !== 'undefined') {
    if (window.__ENABLE_IDLE_VILLAGE_TEST_HOOKS) {
      return true;
    }
    if (window.__ENABLE_IDLE_VILLAGE_DIAGNOSTICS) {
      return true;
    }
  }

  if (typeof import.meta !== 'undefined') {
    const env = (import.meta.env ?? {}) as IdleVillageDiagnosticsEnv;
    if (env.VITE_IDLE_VILLAGE_DIAGNOSTICS === 'true' || env.VITE_ENABLE_SANDBOX_DIAGNOSTICS === 'true') {
      return true;
    }
  }

  return false;
};

const isDiagnosticsEnabled = (): boolean => isSandboxDiagnosticsRuntimeEnabled();

/**
 * Emits a diagnostics message when the current environment enables it.
 */
const emit = (
  level: 'log' | 'info' | 'warn' | 'debug',
  scope: string,
  message: string,
  payload?: unknown,
) => {
  if (!isDiagnosticsEnabled()) {
    return;
  }

  const prefix = `[IdleVillageSandbox:${scope}] ${message}`;
  if (payload !== undefined) {
    console[level](prefix, payload);
  } else {
    console[level](prefix);
  }
};

/**
 * Logging helpers that only emit when diagnostics are enabled.
 */
export interface SandboxDiagnostics<TPayload = unknown> {
  /** Emits a log-level message. */
  log: (message: string, payload?: TPayload, tags?: string[]) => void;
  /** Emits an info-level message. */
  info: (message: string, payload?: TPayload, tags?: string[]) => void;
  /** Emits a warn-level message. */
  warn: (message: string, payload?: TPayload, tags?: string[]) => void;
  /** Emits a debug-level message. */
  debug: (message: string, payload?: TPayload, tags?: string[]) => void;
  /** Emits an error-level message. */
  error: (message: string, payload?: TPayload, tags?: string[]) => void;
  /** Returns true when diagnostics will emit output. */
  isEnabled: () => boolean;
}

/**
 * Factory that scopes sandbox diagnostics to a specific module and channel.
 */
export function createSandboxDiagnostics<TPayload = unknown>(
  scope: string,
  channel: DiagnosticsChannelId = 'picker',
): SandboxDiagnostics<TPayload> {
  const buildLogger =
    (level: DiagnosticLog['level']) =>
    (message: string, payload?: TPayload, tags?: string[]) => {
      const consoleLevel = level === 'error' ? 'warn' : (level as 'log' | 'info' | 'warn' | 'debug');
      emit(consoleLevel, scope, message, payload);
      recordLog({
        channel,
        timestamp: Date.now(),
        level,
        scope,
        message,
        payload,
        tags,
      });
    };

  return {
    log: buildLogger('log'),
    info: buildLogger('info'),
    warn: buildLogger('warn'),
    debug: buildLogger('debug'),
    error: buildLogger('error'),
    isEnabled: () => isDiagnosticsEnabled(),
  };
}

export const createSandboxDiagnosticsChannel = createSandboxDiagnostics;
