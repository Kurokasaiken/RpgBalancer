declare global {
  interface Window {
    __ENABLE_IDLE_VILLAGE_TEST_HOOKS?: boolean;
    __ENABLE_IDLE_VILLAGE_DIAGNOSTICS?: boolean;
  }
}

export type DiagnosticsChannelId =
  | 'picker'
  | 'validators'
  | 'risk'
  | 'theater'
  | 'drag'
  | (string & {});

export type PickerDiagnosticsPayload = {
  slotId?: string | null;
  residentId?: string | null;
  action?: string;
  details?: Record<string, unknown>;
  [key: string]: unknown;
};

export type ValidatorDiagnosticsPayload = {
  slotId?: string;
  residentId?: string | null;
  validation?: Record<string, unknown>;
  dropState?: Record<string, unknown>;
  [key: string]: unknown;
};

export type RiskDiagnosticsPayload = {
  activityId?: string;
  injuryPct?: number;
  deathPct?: number;
  warnings?: string[];
  [key: string]: unknown;
};

export type TheaterDiagnosticsPayload = {
  primarySlotId?: string | null;
  resolvedPrimarySlotId?: string | null;
  previewIds?: string[];
  action?: string;
  [key: string]: unknown;
};

/**
 * Diagnostic log entry for the unified bundle.
 */
export interface DiagnosticLog<TPayload = unknown> {
  /** Logical channel (picker, validators, risk, etc.). */
  channel: DiagnosticsChannelId;
  /** UNIX timestamp (ms) for chronological sort. */
  timestamp: number;
  /** Severity level. */
  level: 'log' | 'info' | 'warn' | 'debug' | 'error';
  /** Logical scope/component name. */
  scope: string;
  /** Human-friendly message. */
  message: string;
  /** Optional payload for structured context. */
  payload?: TPayload;
  /** Optional tags for filtering (e.g., ['drag', 'quest']). */
  tags?: string[];
}

/**
 * Descriptor for a diagnostics channel exposed to the panel.
 */
interface ChannelDefinition<TPayload = unknown> {
  /** Unique identifier (matches DiagnosticLog.channel). */
  id: DiagnosticsChannelId;
  /** UI label. */
  label: string;
  /** Description for tooltips/docs. */
  description: string;
  /** Optional per-channel buffer size (default 400). */
  bufferSize?: number;
  /** Optional formatter run before persisting a log entry. */
  formatter?: (entry: DiagnosticLog<TPayload>) => DiagnosticLog;
}

export type ChannelRegistry = Record<DiagnosticsChannelId, ChannelDefinition>;

/**
 * Filter options for extracting diagnostic logs.
 */
export interface DiagnosticsFilter {
  /** Channel to filter by (omit = all). */
  channel?: DiagnosticsChannelId;
  /** Only include logs newer than this timestamp. */
  since?: number;
  /** Require at least one matching tag. */
  tags?: string[];
}

