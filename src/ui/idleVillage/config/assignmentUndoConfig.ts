/**
 * Utility functions for assignment undo configuration
 */

/**
 * Generate unique change ID
 */
export function generateChangeId(): string {
  return `change-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
}

/**
 * Generate checksum for assignment state
 */
export function generateStateChecksum(state: AssignmentState): string {
  const data = JSON.stringify(state);
  let hash = 0;
  for (let i = 0; i < data.length; i++) {
    const char = data.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32-bit integer
  }
  return hash.toString(36);
}

/**
 * Get keyboard shortcut for current platform
 */
export function getPlatformShortcut(shortcut: KeyboardShortcutConfig): string {
  const platform = navigator.platform.toLowerCase();
  
  if (platform.includes('mac') && shortcut.platformVariants?.mac) {
    return shortcut.platformVariants.mac;
  }
  if (platform.includes('win') && shortcut.platformVariants?.windows) {
    return shortcut.platformVariants.windows;
  }
  if (platform.includes('linux') && shortcut.platformVariants?.linux) {
    return shortcut.platformVariants.linux;
  }
  
  return shortcut.key;
}

/**
 * Format timestamp for display
 */
export function formatTimestamp(timestamp: number): string {
  const date = new Date(timestamp);
  return date.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
  });
}

/**
 * Calculate change priority based on impact
 */
export function calculateChangePriority(impact: AssignmentDiffSummary['impact']): 'low' | 'medium' | 'high' | 'critical' {
  if (impact.affectedResidents >= 10 || impact.productivityImpact >= 0.7) {
    return 'critical';
  }
  if (impact.affectedResidents >= 5 || impact.productivityImpact >= 0.4) {
    return 'high';
  }
  if (impact.affectedResidents >= 2 || impact.productivityImpact >= 0.2) {
    return 'medium';
  }
  return 'low';
}

/**
 * Get color for change type
 */
export function getChangeTypeColor(type: AssignmentChangeType, config: AssignmentUndoConfig): string {
  return config.ui.visual.changeTypeColors[type];
}

/**
 * Get icon for change type
 */
export function getChangeTypeIcon(type: AssignmentChangeType): string {
  switch (type) {
    case AssignmentChangeType.RESIDENT_ASSIGNED:
      return '➕';
    case AssignmentChangeType.RESIDENT_UNASSIGNED:
      return '➖';
    case AssignmentChangeType.RESIDENT_MOVED:
      return '↔️';
    case AssignmentChangeType.ACTIVITY_CHANGED:
      return '🔄';
    case AssignmentChangeType.BATCH_ASSIGNMENT:
      return '📋';
    case AssignmentChangeType.BATCH_UNASSIGNMENT:
      return '🗑️';
    case AssignmentChangeType.EMERGENCY_REASSIGNMENT:
      return '🚨';
    case AssignmentChangeType.AUTO_ASSIGNMENT:
      return '🤖';
    default:
      return '📝';
  }
}
