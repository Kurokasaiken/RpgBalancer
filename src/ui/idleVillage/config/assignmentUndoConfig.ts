/**
 * Assignment change types for undo/redo tracking
 */
export enum AssignmentChangeType {
  RESIDENT_ASSIGNED = 'resident_assigned',
  RESIDENT_UNASSIGNED = 'resident_unassigned',
  RESIDENT_MOVED = 'resident_moved',
  ACTIVITY_CHANGED = 'activity_changed',
  BATCH_ASSIGNMENT = 'batch_assignment',
  BATCH_UNASSIGNMENT = 'batch_unassignment',
  EMERGENCY_REASSIGNMENT = 'emergency_reassignment',
  AUTO_ASSIGNMENT = 'auto_assignment',
}

/**
 * Keyboard shortcut configuration
 */
export interface KeyboardShortcutConfig {
  /** Key combination (e.g., 'Ctrl+Z', 'Cmd+Z') */
  key: string;
  /** Action to perform */
  action: 'undo' | 'redo' | 'clear_history' | 'toggle_timeline';
  /** Whether shortcut is enabled */
  enabled: boolean;
  /** Description for UI display */
  description: string;
  /** Platform-specific variants */
  platformVariants?: {
    mac?: string;
    windows?: string;
    linux?: string;
  };
}

/**
 * Assignment change entry for timeline
 */
export interface AssignmentChange {
  /** Unique identifier for the change */
  id: string;
  /** Type of change */
  type: AssignmentChangeType;
  /** Timestamp when change occurred */
  timestamp: number;
  /** Description of the change */
  description: string;
  /** Previous state (before change) */
  previousState: AssignmentState;
  /** New state (after change) */
  newState: AssignmentState;
  /** User who made the change */
  userId?: string;
  /** Session identifier */
  sessionId: string;
  /** Whether change was automatically generated */
  autoGenerated: boolean;
  /** Additional metadata */
  metadata: {
    affectedResidents: string[];
    affectedActivities: string[];
    reason?: string;
    priority?: number;
    context?: Record<string, unknown>;
  };
}

/**
 * Assignment state snapshot
 */
export interface AssignmentState {
  /** Resident assignments */
  assignments: Record<string, string>; // residentId -> activityId
  /** Activity capacities */
  activityCapacities: Record<string, number>;
  /** Resident availability */
  residentAvailability: Record<string, boolean>;
  /** Activity requirements */
  activityRequirements: Record<string, string[]>; // activityId -> requiredSpecializations
  /** Timestamp of snapshot */
  timestamp: number;
  /** Checksum for integrity verification */
  checksum: string;
}

/**
 * Diff summary for assignment changes
 */
export interface AssignmentDiffSummary {
  /** Change ID */
  changeId: string;
  /** Type of change */
  type: AssignmentChangeType;
  /** Brief description */
  summary: string;
  /** Detailed changes */
  details: {
    /** Residents added to activities */
    added: Array<{
      residentId: string;
      residentName: string;
      activityId: string;
      activityName: string;
    }>;
    /** Residents removed from activities */
    removed: Array<{
      residentId: string;
      residentName: string;
      activityId: string;
      activityName: string;
    }>;
    /** Residents moved between activities */
    moved: Array<{
      residentId: string;
      residentName: string;
      fromActivityId: string;
      fromActivityName: string;
      toActivityId: string;
      toActivityName: string;
    }>;
  };
  /** Impact metrics */
  impact: {
    /** Number of affected residents */
    affectedResidents: number;
    /** Number of affected activities */
    affectedActivities: number;
    /** Priority level of change */
    priority: 'low' | 'medium' | 'high' | 'critical';
    /** Estimated impact on productivity */
    productivityImpact: number; // -1 to 1 scale
  };
  /** Timestamp */
  timestamp: number;
}

