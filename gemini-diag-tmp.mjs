import { chromium } from 'playwright';
const b = await chromium.connectOverCDP('http://127.0.0.1:9222');
const ctx = b.contexts()[0];
console.log('pages:', ctx.pages().map(p=>p.url().slice(0,80)));
const p = await ctx.newPage();
await p.goto('https://gemini.google.com/app', {waitUntil:'commit', timeout:60000});
await p.waitForTimeout(15000);
console.log('url:', p.url(), '| title:', await p.title());
const labels = await p.$$eval('button', els => els.map(e=>e.getAttribute('aria-label')).filter(Boolean));
console.log('buttons:', labels.filter(l=>/carica|upload|allega|file|plus|aggiungi/i.test(l)));
const ed = await p.$$('div[contenteditable="true"], .ql-editor, textarea');
console.log('composer:', ed.length);
await b.close();
