import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', e => console.log('[err]', String(e).slice(0,120)));
await p.goto('http://localhost:5173/game', { waitUntil: 'domcontentloaded', timeout: 45000 });
await p.waitForTimeout(9000);
await p.click('[aria-label="Stash"]');
await p.waitForTimeout(2500);
await p.screenshot({ path: '.mw/runs/20261120-piastrina-icone/gen/live-stash.png' });
const chest = await p.evaluate(() => [...document.querySelectorAll('img')].map(i=>i.src).filter(s=>/chest|emblem/i.test(s)));
console.log('chest imgs:', JSON.stringify(chest));
await b.close();
console.log('done');
