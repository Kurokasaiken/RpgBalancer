#!/usr/bin/env python3
"""PLAN-110 C1 band + crest: approved Gemini originals -> runtime assets + geometry.

spine : cut, crop, seamless vertical tile (cross-fade of the period's tail into its head)
joint : clasp on a piece of band; scaled so its band width equals the spine's
end   : band end + pendant; same band-width rule
crest : the piece on top of the column; scaled to CREST_H
Same cut and colour grade as build-roster-assets.py (one source of truth for both).

Usage: tools/hud-real/venv/bin/python scripts/hud-real/build-band-assets.py \
         --spine S.png --joint J.png --end E.png --crest C.png \
         [--out public/assets/ui/hud-real/C1] [--ts src/ui/idleVillage/hudReal/c1BandGeometry.ts]
"""
import argparse
import importlib.util
import json
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py'))
bra = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bra)

BAND_W = 29.0    # design px: mockup spine x 18..48 src x 1600/1672
CREST_H = 196.0  # design px: close to the mockup emblem height


def band_width(alpha, rows):
    """Median opaque width over the given rows (the band as it enters the piece)."""
    w = [(alpha[y] > 0.5).sum() for y in rows]
    return float(np.median([v for v in w if v > 0]))


def spine(path, out):
    rgb, a, *_ = bra.cut(path)
    rgb, a, _ = bra.crop_to(rgb, a, pad=0)
    h = rgb.shape[0]
    seg = np.dstack([rgb.astype(np.float32), a])[int(h * 0.1):int(h * 0.9)]
    fade = max(8, seg.shape[0] // 10)
    L = seg.shape[0] - fade
    tile = seg[:L].copy()
    w = np.linspace(0, 1, fade)[:, None, None]
    tile[:fade] = seg[L:L + fade] * (1 - w) + seg[:fade] * w
    trgb, ta = tile[..., :3].astype(np.uint8), tile[..., 3]
    s = BAND_W / band_width(ta, range(0, ta.shape[0], 4))
    bra.save(trgb, ta, s, os.path.join(out, 'band-tile.webp'))
    return {'w': round(trgb.shape[1] * s, 2), 'h': round(trgb.shape[0] * s, 2)}


def banded(path, out, name, rows_frac):
    rgb, a, *_ = bra.cut(path)
    rgb, a, _ = bra.crop_to(rgb, a, pad=2)
    h = rgb.shape[0]
    rows = range(int(h * rows_frac[0]), int(h * rows_frac[1]))
    s = BAND_W / band_width(a, rows)
    cols = np.where((a[list(rows)] > 0.5).any(0))[0]
    band_cx = (cols.min() + cols.max()) / 2
    bra.save(rgb, a, s, os.path.join(out, f'{name}.webp'))
    return {'w': round(rgb.shape[1] * s, 2), 'h': round(rgb.shape[0] * s, 2), 'bandCx': round(band_cx * s, 2)}


def crest(path, out):
    rgb, a, *_ = bra.cut(path)
    rgb, a, _ = bra.crop_to(rgb, a, pad=2)
    s = CREST_H / rgb.shape[0]
    bra.save(rgb, a, s, os.path.join(out, 'crest.webp'))
    return {'w': round(rgb.shape[1] * s, 2), 'h': round(rgb.shape[0] * s, 2)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spine', required=True)
    ap.add_argument('--joint', required=True)
    ap.add_argument('--end', required=True)
    ap.add_argument('--crest', required=True)
    ap.add_argument('--out', default='public/assets/ui/hud-real/C1')
    ap.add_argument('--ts')
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    geo = {
        'bandW': BAND_W,
        'tile': spine(a.spine, a.out),
        'joint': banded(a.joint, a.out, 'band-joint', (0.0, 0.12)),
        'end': banded(a.end, a.out, 'band-end', (0.0, 0.3)),
        'crest': crest(a.crest, a.out),
        'source': {'spine': a.spine, 'joint': a.joint, 'end': a.end, 'crest': a.crest},
    }
    with open(os.path.join(a.out, 'band-geometry.json'), 'w') as f:
        json.dump(geo, f, indent=2)
    if a.ts:
        body = {k: v for k, v in geo.items() if k != 'source'}
        with open(a.ts, 'w') as f:
            f.write('/**\n * GENERATED by scripts/hud-real/build-band-assets.py — do not edit by hand.\n'
                    ' * Band, clasp, band end and crest of the C1 roster column. Units: design px; assets 2x.\n */\n')
            f.write('export const C1_BAND = ' + json.dumps(body, indent=2) + ' as const;\n')
    print(json.dumps({k: v for k, v in geo.items() if k != 'source'}, indent=1))


if __name__ == '__main__':
    main()
