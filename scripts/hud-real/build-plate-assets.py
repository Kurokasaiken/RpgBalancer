#!/usr/bin/env python3
"""PLAN-110 medallion + empty plaque pieces (compass readout C5, narrator voice C10) -> asset + geometry.

Cut + grade like the other pieces, scaled to --width design px, exported 2x. The text field is the
largest emerald-enamel region right of --split (fraction of width), eroded so the gold rails stay out.
Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-plate-assets.py --name compass --src P.png --width 330 --split 0.5 --ts file.ts
"""
import argparse, importlib.util, json, os
import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py'))
bra = importlib.util.module_from_spec(spec); spec.loader.exec_module(bra)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True); ap.add_argument('--src', required=True)
    ap.add_argument('--width', type=float, required=True); ap.add_argument('--split', type=float, default=0.5)
    ap.add_argument('--out'); ap.add_argument('--ts')
    a = ap.parse_args()
    out = a.out or f'public/assets/ui/hud-real/{a.name}'
    os.makedirs(out, exist_ok=True)
    rgb, alpha, *_ = bra.cut(a.src)
    crgb, ca, _ = bra.crop_to(rgb, alpha, pad=2)
    h, w = ca.shape
    s = a.width / w
    f = crgb.astype(np.int32)
    lum = (f[..., 0] * 299 + f[..., 1] * 587 + f[..., 2] * 114) // 1000
    green = (ca > 0.5) & (f[..., 1] > f[..., 0] + 15) & (f[..., 1] >= f[..., 2] - 25) & (lum > 20) & (lum < 150)
    green[:, :int(w * a.split)] = False
    k = max(5, int(w * 0.012)) | 1
    green = cv2.morphologyEx(green.astype(np.uint8), cv2.MORPH_OPEN, np.ones((k, k), np.uint8))
    green = cv2.erode(green, np.ones((k, k), np.uint8))
    n, lab, st, _ = cv2.connectedComponentsWithStats(green, connectivity=4)
    i = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
    x, y, ww, hh = (int(st[i, c]) for c in (cv2.CC_STAT_LEFT, cv2.CC_STAT_TOP, cv2.CC_STAT_WIDTH, cv2.CC_STAT_HEIGHT))
    size = bra.save(crgb, ca, s, os.path.join(out, 'piece.webp'))
    geo = {'w': round(w * s, 2), 'h': round(h * s, 2),
           'field': {'x': round(x * s, 2), 'y': round(y * s, 2), 'w': round(ww * s, 2), 'h': round(hh * s, 2)},
           'asset2x': list(size)}
    json.dump(geo, open(os.path.join(out, 'piece-geometry.json'), 'w'), indent=2)
    if a.ts:
        const = ''.join(p.capitalize() for p in a.name.split('-')).upper()
        open(a.ts, 'w').write(f'/**\n * GENERATED by scripts/hud-real/build-plate-assets.py ({a.name}) — do not edit by hand.\n'
                               ' * Medallion + plaque image; `field` = the empty enamel plaque where live text sits. Design px; asset 2x.\n */\n'
                               f'export const {const}_PIECE = ' + json.dumps(geo, indent=2) + ' as const;\n')
    print(json.dumps(geo))


if __name__ == '__main__':
    main()
