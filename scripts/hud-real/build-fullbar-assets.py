#!/usr/bin/env python3
"""PLAN-110 full bar (one generated image with N slots) -> runtime asset + slot geometry.

Used for the resource bar (3 slots = gold, food, wood). The bar is cut from the flat navy
background, graded, scaled so a slot is SLOT_H design px high (mockup: ~46), exported 2x.
Slots = dark-glass regions along the bar's middle row, measured on the alpha.

Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-fullbar-assets.py --name resources \
         --bar B.png --slots 3 [--slot-h 46] [--out public/assets/ui/hud-real/<name>] [--ts file.ts]
"""
import argparse
import importlib.util
import json
import os

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, fname):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, fname))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


bra = _load('bra', 'build-roster-assets.py')


def luma(rgb):
    return (rgb[..., 0] * 299 + rgb[..., 1] * 587 + rgb[..., 2] * 114) // 1000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True)
    ap.add_argument('--bar', required=True)
    ap.add_argument('--slots', type=int, required=True)
    ap.add_argument('--slot-h', type=float, default=46.0)
    ap.add_argument('--square', action='store_true', help='only near-square slots (round sockets)')
    ap.add_argument('--field', action='store_true', help='also measure the largest wide dark-glass field (not a slot)')
    ap.add_argument('--out')
    ap.add_argument('--ts')
    a = ap.parse_args()
    out = a.out or f'public/assets/ui/hud-real/{a.name}'
    os.makedirs(out, exist_ok=True)
    rgb, alpha, *_ = bra.cut(a.bar)
    crgb, ca, (ox, oy) = bra.crop_to(rgb, alpha, pad=2)
    h, w = ca.shape
    lum = luma(crgb.astype(np.int32))
    dark = ((lum < 40) & (ca > 0.5)).astype(np.uint8)
    n, lab, st, cen = cv2.connectedComponentsWithStats(dark, connectivity=4)
    cand = [i for i in range(1, n) if st[i, cv2.CC_STAT_AREA] > 0.004 * w * h and st[i, cv2.CC_STAT_WIDTH] > 0.8 * st[i, cv2.CC_STAT_HEIGHT]
            and (not a.square or st[i, cv2.CC_STAT_WIDTH] < 1.25 * st[i, cv2.CC_STAT_HEIGHT])]
    cand.sort(key=lambda i: -st[i, cv2.CC_STAT_AREA])
    cand = sorted(cand[:a.slots], key=lambda i: cen[i][0])
    if len(cand) != a.slots:
        raise SystemExit(f'found {len(cand)} slots, expected {a.slots}')
    chosen = set(cand)
    slot_hs = [st[i, cv2.CC_STAT_HEIGHT] for i in cand]
    s = a.slot_h / float(np.median(slot_hs))
    size = bra.save(crgb, ca, s, os.path.join(out, 'bar.webp'))
    slots = []
    for i in cand:
        x, y, ww, hh, _ = st[i]
        slots.append({'x': round(x * s, 2), 'y': round(y * s, 2), 'w': round(ww * s, 2), 'h': round(hh * s, 2)})
    field = None
    if a.field:
        k = np.ones((max(9, int(0.03 * w)) | 1,) * 2, np.uint8)
        d2 = cv2.erode(dark, k)
        n2, lab2, st2, _ = cv2.connectedComponentsWithStats(d2, connectivity=4)
        fc = [i for i in range(1, n2) if st2[i, cv2.CC_STAT_WIDTH] > 1.3 * st2[i, cv2.CC_STAT_HEIGHT]]
        fc.sort(key=lambda i: -st2[i, cv2.CC_STAT_AREA])
        if fc:
            x, y, ww, hh, _ = st2[fc[0]]
            pad = k.shape[0] // 2
            x, y, ww, hh = x - pad, y - pad, ww + 2 * pad, hh + 2 * pad
            field = {'x': round(x * s, 2), 'y': round(y * s, 2), 'w': round(ww * s, 2), 'h': round(hh * s, 2)}
    geo = {'w': round(w * s, 2), 'h': round(h * s, 2), 'slots': slots, **({'field': field} if field else {}), 'asset2x': list(size), 'source': a.bar}
    with open(os.path.join(out, 'bar-geometry.json'), 'w') as f:
        json.dump(geo, f, indent=2)
    if a.ts:
        const = ''.join(p.capitalize() for p in a.name.split('-')).upper()
        with open(a.ts, 'w') as f:
            f.write(f'/**\n * GENERATED by scripts/hud-real/build-fullbar-assets.py ({a.name}) — do not edit by hand.\n'
                    ' * One bar image; `slots` are the dark-glass boxes where live content sits. Design px; asset 2x.\n */\n')
            f.write(f'export const {const}_BAR = ' + json.dumps({k: v for k, v in geo.items() if k != 'source'}, indent=2) + ' as const;\n')
    print(json.dumps(geo, indent=1))


if __name__ == '__main__':
    main()
