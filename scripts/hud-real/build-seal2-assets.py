#!/usr/bin/env python3
"""PLAN-110 C7 v2: light victory seal. One generated image with a thin gold laurel ring (empty teal disc) and a separate empty strip
-> disc.webp + strip.webp (same scale) and geometry (disc field circle, strip field box). Cut + gold grade like the other pieces.
Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-seal2-assets.py --src S.png --width 190 --ts src/ui/idleVillage/hudReal/seal2Geometry.ts"""
import argparse, importlib.util, json, os
import cv2, numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py')); bra = importlib.util.module_from_spec(spec); spec.loader.exec_module(bra)
ap = argparse.ArgumentParser(); ap.add_argument('--src', required=True); ap.add_argument('--width', type=float, default=190); ap.add_argument('--out', default='public/assets/ui/hud-real/seal'); ap.add_argument('--ts'); a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)
rgb, alpha, *_ = bra.cut(a.src)
H, W = alpha.shape
rows = (alpha > 0.5).sum(1)
# gap between ring and strip: empty rows after the ring
ys = np.where(rows > 3)[0]; gaps = [(ys[i], ys[i + 1]) for i in range(len(ys) - 1) if ys[i + 1] - ys[i] > 4]
split = (gaps[-1][0] + gaps[-1][1]) // 2 if gaps else int(H * 0.75)
def part(y0, y1):
    al = alpha.copy(); al[:y0] = 0; al[y1:] = 0
    return bra.crop_to(rgb, al, pad=2)
drgb, da, (dx, dy) = part(0, split); srgb, sa, (sx, sy) = part(split, H)
dh, dw = da.shape; s = a.width / dw
# disc interior: the biggest dark-teal blob in the disc part, as circle (cx, cy, r)
f = drgb.astype(np.int32); lum = (f[..., 0] * 299 + f[..., 1] * 587 + f[..., 2] * 114) // 1000
teal = ((da > 0.5) & (lum < 120) & (f[..., 1] >= f[..., 0] + 5)).astype(np.uint8)
teal = cv2.morphologyEx(teal, cv2.MORPH_OPEN, np.ones((9, 9), np.uint8))
n, lab, st, cen = cv2.connectedComponentsWithStats(teal); i = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
x, y, w_, h_ = (int(st[i, c]) for c in (cv2.CC_STAT_LEFT, cv2.CC_STAT_TOP, cv2.CC_STAT_WIDTH, cv2.CC_STAT_HEIGHT))
r = min(w_, h_) / 2.0 * 0.94
disc = {'cx': round((x + w_ / 2) * s, 2), 'cy': round((y + h_ / 2) * s, 2), 'r': round(r * s, 2)}
sh, sw = sa.shape; sf = srgb.astype(np.int32); sl = (sf[..., 0] * 299 + sf[..., 1] * 587 + sf[..., 2] * 114) // 1000
st_m = ((sa > 0.5) & (sl < 120) & (sf[..., 1] >= sf[..., 0] + 5)).astype(np.uint8)
st_m = cv2.erode(cv2.morphologyEx(st_m, cv2.MORPH_OPEN, np.ones((7, 7), np.uint8)), np.ones((5, 5), np.uint8))
n2, l2, s2, _ = cv2.connectedComponentsWithStats(st_m); j = 1 + int(np.argmax(s2[1:, cv2.CC_STAT_AREA]))
fx, fy, fw, fh = (int(s2[j, c]) for c in (cv2.CC_STAT_LEFT, cv2.CC_STAT_TOP, cv2.CC_STAT_WIDTH, cv2.CC_STAT_HEIGHT))
dsz = bra.save(drgb, da, s, os.path.join(a.out, 'disc.webp')); ssz = bra.save(srgb, sa, s, os.path.join(a.out, 'strip.webp'))
geo = {'disc': {'w': round(dw * s, 2), 'h': round(dh * s, 2), **disc, 'asset2x': list(dsz)},
       'strip': {'w': round(sw * s, 2), 'h': round(sh * s, 2), 'offsetX': round((sx - dx) * s, 2), 'field': {'x': round(fx * s, 2), 'y': round(fy * s, 2), 'w': round(fw * s, 2), 'h': round(fh * s, 2)}, 'asset2x': list(ssz)},
       'gap': round(((sy + 0) - (dy + dh)) * s, 2)}
print(json.dumps(geo))
if a.ts:
    open(a.ts, 'w').write('/** GENERATED by scripts/hud-real/build-seal2-assets.py — do not edit by hand. Disc (ring + laurel, empty teal glass: circle field) and strip (empty). Design px; assets 2x. */\nexport const SEAL2 = ' + json.dumps(geo, indent=2) + ' as const;\n')
