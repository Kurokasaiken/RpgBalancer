#!/usr/bin/env python3
"""PLAN-110 C1 row module: one Gemini module (vertical band + portrait ring fused to it)
-> two runtime pieces that tile into the roster column like the chosen mockup.

  ring-fused.webp : the ring with its crescent, cut where the band starts (the band is drawn
                    separately, continuous, so it never shows a seam between rows)
  band-mod.webp   : the band strip of the module, made seamless vertically (cross-fade)
Both share one scale: the ring's outer diameter = RING_D design px (mockup measure).
Same cut and colour grade as build-roster-assets.py.

Usage: tools/hud-real/venv/bin/python scripts/hud-real/build-rowmod-assets.py --module M.png \
         [--out public/assets/ui/hud-real/C1] [--ts src/ui/idleVillage/hudReal/c1RowModGeometry.ts]
"""
import argparse
import importlib.util
import json
import os

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py'))
bra = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bra)

RING_D = bra.RING_D


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--module', required=True)
    ap.add_argument('--out', default='public/assets/ui/hud-real/C1')
    ap.add_argument('--ts')
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rgb, alpha, near, lab, border = bra.cut(a.module)
    h, w = alpha.shape
    # band = columns opaque on (almost) every row
    colfill = (alpha > 0.5).mean(0)
    band_cols = np.where(colfill > 0.97)[0]
    bx0, bx1 = int(band_cols.min()), int(band_cols.max())
    # portrait hole = largest enclosed navy component; fit circle
    sizes = [(int((lab == i).sum()), i) for i in range(1, lab.max() + 1) if i not in border]
    hole = (lab == max(sizes)[1]).astype(np.uint8)
    cnt = max(cv2.findContours(hole, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)[0], key=len)[:, 0, :].astype(float)
    hcx, hcy, hr = bra.fit_circle(cnt)
    # ring outer extent: opaque pixels right of the band, on the ring's rows
    ring_mask = (alpha > 0.5).copy()
    ring_mask[:, :bx1 + 1 + int(0.03 * w)] = False   # skip the band's partial edge columns
    ys, xs = np.where(ring_mask)
    outer_d = max(xs.max() - (2 * hcx - xs.max()), ys.max() - ys.min())
    s = RING_D / outer_d
    # ring piece: everything from the band's right half outwards (crescent overlaps the band)
    cut_x = (bx0 + bx1) // 2
    ra = alpha.copy()
    ra[:, :cut_x] = 0
    ra[hole > 0] = 0
    ry0, ry1 = max(0, ys.min() - 4), min(h, ys.max() + 5)
    ring_rgb, ring_a = rgb[ry0:ry1, cut_x:], ra[ry0:ry1, cut_x:]
    bra.save(ring_rgb, ring_a, s, os.path.join(a.out, 'ring-fused.webp'))
    # band tile: the band columns where nothing of the ring overlaps them. The crescent fuses into
    # the band near the ring's centre row, so take the rows above and below it and join them.
    free = np.ones(h, bool)
    free[max(0, ys.min() - 4):min(h, ys.max() + 5)] = False   # rows the ring (and its crescent) occupies
    runs, start = [], None
    for y in range(h + 1):
        f = y < h and free[y]
        if f and start is None:
            start = y
        elif not f and start is not None:
            runs.append((start, y)); start = None
    parts = [np.dstack([rgb[y0:y1, bx0:bx1 + 1].astype(np.float32), alpha[y0:y1, bx0:bx1 + 1]]) for y0, y1 in runs if y1 - y0 >= 12]
    if not parts:
        raise SystemExit('no ring-free band rows in this module')
    seg = np.concatenate(parts, axis=0)
    fade = max(6, min(seg.shape[0] // 4, 40))
    L = seg.shape[0] - fade
    tile = seg[:L].copy()
    wv = np.linspace(0, 1, fade)[:, None, None]
    tile[:fade] = seg[L:L + fade] * (1 - wv) + seg[:fade] * wv
    bra.save(tile[..., :3].astype(np.uint8), tile[..., 3], s, os.path.join(a.out, 'band-mod.webp'))
    geo = {
        'ring': {'w': round(ring_rgb.shape[1] * s, 2), 'h': round(ring_rgb.shape[0] * s, 2),
                 'hole': {'cx': round((hcx - cut_x) * s, 2), 'cy': round((hcy - ry0) * s, 2), 'r': round(hr * s, 2)}},
        'band': {'w': round((bx1 - bx0 + 1) * s, 2), 'tileH': round(tile.shape[0] * s, 2),
                 'offsetFromHoleCx': round((bx0 - hcx) * s, 2), 'ringLeftFromBand': round((cut_x - bx0) * s, 2)},
        'source': a.module,
    }
    with open(os.path.join(a.out, 'rowmod-geometry.json'), 'w') as f:
        json.dump(geo, f, indent=2)
    if a.ts:
        with open(a.ts, 'w') as f:
            f.write('/**\n * GENERATED by scripts/hud-real/build-rowmod-assets.py — do not edit by hand.\n'
                    ' * Row module of the C1 roster: ring fused to the band + seamless band. Design px; assets 2x.\n */\n')
            f.write('export const C1_ROWMOD = ' + json.dumps({k: v for k, v in geo.items() if k != 'source'}, indent=2) + ' as const;\n')
    print(json.dumps(geo, indent=1))


if __name__ == '__main__':
    main()
