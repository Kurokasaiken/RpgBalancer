#!/usr/bin/env python3
"""PLAN-112 F4: slim top-row bars for the signed blueprint (top row H=56 CSS px).

Surgery on the already-approved assets (vivid pre-G2-4 palette restored by Director ruling):

  - slot/socket band kept at native size; ornament bands squashed to thin trim;
  - LEFT CLOSURE IS A UNIT: for resources the caged-gem medallion + end-cap frame + hanging
    teardrop pendant are kept whole (Director: the pendant hangs UNDER the component, the cage
    must be big enough to close the bar's end). The cluster is scaled uniformly and overlaid on
    the pill's left end like the original bar does;
  - the pill is stretched horizontally to the signed slot width.

Outputs per bar: `bar-slim.webp` (2x) + `bar-slim-geometry.json` + a generated `*Geometry.ts`.
Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-slim-bars.py
"""
import json
import os

import cv2
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def over(base, img, x0, y0):
    h, w = img.shape[:2]
    reg = base[y0:y0 + h, x0:x0 + w]
    a = img[..., 3:4].astype(np.float32) / 255.0
    reg[..., :3] = img[..., :3] * a + reg[..., :3] * (1 - a)
    reg[..., 3] = np.maximum(reg[..., 3], img[..., 3])


def luma(bgr):
    return (bgr[..., 0].astype(np.int32) * 29 + bgr[..., 1].astype(np.int32) * 59 + bgr[..., 2].astype(np.int32) * 11) // 100


def squash_bands(pill, y0, y1, band_px):
    top = cv2.resize(pill[:y0], (pill.shape[1], band_px), interpolation=cv2.INTER_AREA)
    bot = cv2.resize(pill[y1:], (pill.shape[1], band_px), interpolation=cv2.INTER_AREA)
    return np.vstack([top, pill[y0:y1], bot]), band_px


def dark_slots(img, count, square=False):
    a = img[..., 3]
    lum = luma(img[..., :3])
    dark = ((lum < 40) & (a > 0.5)).astype(np.uint8)
    n, _, st, cen = cv2.connectedComponentsWithStats(dark, connectivity=4)
    h, w = a.shape
    cand = [i for i in range(1, n)
            if st[i, cv2.CC_STAT_AREA] > 0.004 * w * h and st[i, cv2.CC_STAT_WIDTH] > 0.8 * st[i, cv2.CC_STAT_HEIGHT]
            and (not square or st[i, cv2.CC_STAT_WIDTH] < 1.25 * st[i, cv2.CC_STAT_HEIGHT])]
    cand.sort(key=lambda i: -st[i, cv2.CC_STAT_AREA])
    cand = sorted(cand[:count], key=lambda i: cen[i][0])
    if len(cand) != count:
        raise SystemExit(f'found {len(cand)} dark boxes, expected {count}')
    return [{'x': st[i, 0], 'y': st[i, 1], 'w': st[i, 2], 'h': st[i, 3]} for i in cand]


def widest_dark_field(img):
    a = img[..., 3]
    lum = luma(img[..., :3])
    dark = ((lum < 40) & (a > 0.5)).astype(np.uint8)
    k = np.ones((11, 11), np.uint8)
    d2 = cv2.erode(dark, k)
    n, _, st, _ = cv2.connectedComponentsWithStats(d2, connectivity=4)
    fc = [i for i in range(1, n) if st[i, cv2.CC_STAT_WIDTH] > 1.3 * st[i, cv2.CC_STAT_HEIGHT]]
    if not fc:
        return None
    fc.sort(key=lambda i: -st[i, cv2.CC_STAT_AREA])
    x, y, w, h, _ = st[fc[0]]
    pad = 5
    return {'x': x - pad, 'y': y - pad, 'w': w + 2 * pad, 'h': h + 2 * pad}


def match_gold(img):
    """After downscaling, lift the gold's lightness a touch to sit with the vivid nav astrolabe
    (Director ruling: the pre-G2-4 vivid palette is the reference)."""
    hsv = cv2.cvtColor(img[..., :3], cv2.COLOR_BGR2HSV).astype(np.float32)
    gold = (img[..., 3] > 200) & (hsv[..., 0] >= 10) & (hsv[..., 0] <= 34) & (hsv[..., 1] > 60) & (hsv[..., 2] > 90)
    if gold.sum() < 200:
        return img
    lab = cv2.cvtColor(img[..., :3], cv2.COLOR_BGR2LAB).astype(np.float32)
    lab[..., 0] = np.where(gold, np.clip(lab[..., 0] + 10, 0, 255), lab[..., 0])
    img[..., :3] = cv2.cvtColor(lab.astype(np.uint8), cv2.COLOR_LAB2BGR)
    return img


def save_webp(img, path):
    ys, xs = np.where(img[..., 3] > 8)
    img = img[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    cv2.imwrite(path, img, [cv2.IMWRITE_WEBP_QUALITY, 98])
    return img


def emit(name, img, slots, out_dir, ts_path, field=None, note=''):
    h, w = img.shape[:2]
    geo = {'w': round(w / 2, 2), 'h': round(h / 2, 2),
           'slots': [{k: round(v / 2, 2) for k, v in s.items()} for s in slots],
           'asset2x': [w, h]}
    if field:
        geo['field'] = {k: round(v / 2, 2) for k, v in field.items()}
    with open(os.path.join(out_dir, 'bar-slim-geometry.json'), 'w') as f:
        json.dump(geo, f, indent=2)
    const = name.upper() + '_SLIM'
    body = ('/**\n'
            f' * GENERATED by scripts/hud-real/build-slim-bars.py ({name}) — do not edit by hand.\n'
            f' * Slim top-row bar for the signed blueprint (PLAN-112 F4{note}). Design px; asset 2x.\n */\n'
            f'export const {const}_BAR = ' + json.dumps(geo, indent=2) + ' as const;\n')
    with open(ts_path, 'w') as f:
        f.write(body)
    print(name, json.dumps(geo))


def build_resources():
    im = cv2.imread(f'{ROOT}/public/assets/ui/hud-real/resources/bar.webp', cv2.IMREAD_UNCHANGED)
    # LEFT CLUSTER = caged-gem medallion + end-cap filigree + teardrop pendant (x<220 covers it all).
    # Kept whole and scaled uniformly — the cage closes the bar's left end, the pendant hangs below it.
    cluster = im[:, :220]
    cluster2 = cv2.resize(cluster, (int(cluster.shape[1] * 124 / cluster.shape[0]), 124), interpolation=cv2.INTER_AREA)
    # pill body: slot band native, ornament bands squashed (cut AFTER the end-cap, inside slot 1's left frame)
    pill = im[:180, 208:]
    slim, _ = squash_bands(pill, 40, 138, 10)
    H = 124                                     # the cluster's medallion sets the bar height (62 CSS px)
    W = 720                                     # 360 CSS px x2
    out = np.zeros((H, W, 4), np.uint8)
    # strip's own end-cap is covered by the cluster: lay the strip so slot 1 keeps ~10px of pill margin
    px = cluster2.shape[1] - 12
    pill2 = cv2.resize(slim, (W - px, 116), interpolation=cv2.INTER_AREA)
    out[4:4 + 116, px:] = np.where(pill2[..., 3:4] > 0, pill2, out[4:4 + 116, px:])
    over(out, cluster2, 0, 0)                   # cluster on top, medallion wraps the left end
    out = match_gold(out)
    out = save_webp(out, f'{ROOT}/public/assets/ui/hud-real/resources/bar-slim.webp')
    slots = dark_slots(out, 3)
    # the detector merges the cluster's dark gem with slot 1: clip slot 1 to start at the cluster's
    # right ink edge (measured on the saved asset at the slot's mid-row)
    midy = slots[0]['y'] + slots[0]['h'] // 2
    row = out[midy, :, 3]
    xs = np.where((row > 8) & (np.arange(out.shape[1]) < cluster2.shape[1]))[0]
    if len(xs):
        edge0 = slots[0]['x'] + slots[0]['w']
        slots[0]['x'] = int(xs.max()) + 1
        slots[0]['w'] = edge0 - slots[0]['x']
    emit('resources', out, slots,
         f'{ROOT}/public/assets/ui/hud-real/resources',
         f'{ROOT}/src/ui/idleVillage/hudReal/resourcesSlimGeometry.ts',
         note='; left cluster kept whole (cage + pendant), squashed ornament bands')


def build_time():
    im = cv2.imread(f'{ROOT}/public/assets/ui/hud-real/time/bar.webp', cv2.IMREAD_UNCHANGED)
    # medallion block = dial + gold knot bridge (full ink extent ~x215; the field frame starts ~213)
    med = im[:, :215]
    pill = im[16:, 213:]                        # pill starts inside the field's gold left frame: clean seam
    slim, _ = squash_bands(pill, 34, 118, 14)
    med2 = cv2.resize(med, (int(med.shape[1] * 104 / med.shape[0]), 104), interpolation=cv2.INTER_AREA)
    H = slim.shape[0]
    W = 840                                     # 420 CSS px x2
    out = np.zeros((H, W, 4), np.uint8)
    pw = W - (med2.shape[1] - 14)               # the dial kisses only the pill's left shoulder
    pill2 = cv2.resize(slim, (pw, H), interpolation=cv2.INTER_AREA)
    out[:, -pw:] = pill2
    over(out, med2, 0, (H - 104) // 2)
    out = match_gold(out)
    out = save_webp(out, f'{ROOT}/public/assets/ui/hud-real/time/bar-slim.webp')
    emit('time', out, dark_slots(out, 4, square=True),
         f'{ROOT}/public/assets/ui/hud-real/time',
         f'{ROOT}/src/ui/idleVillage/hudReal/timeSlimGeometry.ts',
         field=widest_dark_field(out),
         note='; squashed ornament bands, native socket row')


if __name__ == '__main__':
    build_resources()
    build_time()
