#!/usr/bin/env python3
"""PLAN-110 roster rail: one generated vertical rail (gold-edged emerald enamel, ivy, gem clasps) -> a seamless repeat tile.
Finds the clasp gems along the rail, picks the clasp-to-clasp period whose two cut rows match best, scales it to --pitch design px
(one row of the roster; two clasps per row by default via --clasps-per-pitch) and exports rail-tile.webp + geometry.
Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-rail-tile.py --src R.png [--pitch 90] [--clasps-per-pitch 2] [--ts file.ts]"""
import argparse, importlib.util, json, os
import cv2, numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py')); bra = importlib.util.module_from_spec(spec); spec.loader.exec_module(bra)
ap = argparse.ArgumentParser(); ap.add_argument('--src', required=True); ap.add_argument('--pitch', type=float, default=90); ap.add_argument('--clasps-per-pitch', type=int, default=2)
ap.add_argument('--out', default='public/assets/ui/hud-real/C1'); ap.add_argument('--ts'); a = ap.parse_args()
rgb, alpha, *_ = bra.cut(a.src); crgb, ca, _ = bra.crop_to(rgb, alpha, pad=0)
h, w = ca.shape
hsv = cv2.cvtColor(crgb, cv2.COLOR_RGB2HSV)
bright_green = ((hsv[..., 0] >= 55) & (hsv[..., 0] <= 100) & (hsv[..., 1] > 120) & (hsv[..., 2] > 150) & (ca > 0.5)).astype(np.float32)
core = bright_green[:, int(w * 0.3):int(w * 0.7)].sum(1)
core = cv2.GaussianBlur(core.reshape(-1, 1), (1, 0), sigmaX=0, sigmaY=max(3, h * 0.01)).ravel()
peaks = [i for i in range(2, h - 2) if core[i] > 0.5 * core.max() and core[i] >= core[i - 2:i + 3].max()]
merged = []
for p in peaks:
    if not merged or p - merged[-1] > h * 0.05: merged.append(p)
print('clasp rows', merged, 'of', h)
best = None
for i in range(len(merged) - 1):
    for j in range(i + 1, len(merged)):
        y0, y1 = merged[i], merged[j]
        if y1 - y0 < h * 0.08: continue
        d = float(np.abs(crgb[y0 - 1:y0 + 2].astype(int).mean(0) - crgb[y1 - 1:y1 + 2].astype(int).mean(0)).mean())
        cand = (d / 1.0 + 0.0 * (y1 - y0), y0, y1)
        if best is None or cand < best: best = cand
_, y0, y1 = best
print('chosen period rows', y0, y1, 'seam diff %.1f' % best[0])
tile = crgb[y0:y1]; ta = ca[y0:y1]
period_px = y1 - y0
unit = a.pitch / a.clasps_per_pitch
s = unit / period_px
os.makedirs(a.out, exist_ok=True)
size = bra.save(tile, ta, s, os.path.join(a.out, 'rail-tile.webp'))
# top cap: from the top of the generated rail down to the first clasp centre (joins the tile, which starts at a clasp centre)
y0c = merged[0]
csize = bra.save(crgb[:y0c], ca[:y0c], s, os.path.join(a.out, 'rail-cap.webp'))
# bottom terminal: from the last clasp row to the end of the generated rail (cap + pendant), same scale, starts on a gem row like the tile
ye = merged[-1]
# (the plain enamel between the last clasp and the cap is cut out so the terminal stays short)
keep_top, keep_bot = int(0.32 * period_px), int(0.55 * period_px)
ert = np.concatenate([crgb[ye:ye + keep_top], crgb[h - keep_bot:]]); eal = np.concatenate([ca[ye:ye + keep_top], ca[h - keep_bot:]])
esize = bra.save(ert, eal, s, os.path.join(a.out, 'rail-end.webp'))
geo = {'w': round(w * s, 2), 'tileH': round(unit, 2), 'endH': round(ert.shape[0] * s, 2), 'capH': round(y0c * s, 2), 'asset2x': list(size), 'endAsset2x': list(esize), 'seamDiff': round(best[0], 1)}
print(json.dumps(geo))
if a.ts:
    open(a.ts, 'w').write('/** GENERATED by scripts/hud-real/build-rail-tile.py — do not edit by hand. Repeat tile of the roster rail (design px, asset 2x). */\nexport const C1_RAIL = ' + json.dumps(geo, indent=2) + ' as const;\n')
