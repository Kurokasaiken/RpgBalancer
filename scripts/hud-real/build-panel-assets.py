#!/usr/bin/env python3
"""PLAN-110 C4 contextual panel frame -> runtime asset + geometry (field, window, plaque).

Cut + grade like the other pieces; scaled so the frame is --width design px wide, exported 2x.
window = dark-glass component; plaque = emerald-enamel component in the lower third;
field = bounding box of the ivory alabaster (bright, low chroma) pixels.
Usage: tools/hud-real/venv/bin/python -I scripts/hud-real/build-panel-assets.py --name panel --src P.png [--width 340] [--ts file.ts]
"""
import argparse, importlib.util, json, os
import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('bra', os.path.join(HERE, 'build-roster-assets.py'))
bra = importlib.util.module_from_spec(spec); spec.loader.exec_module(bra)


def box(mask):
    ys, xs = np.where(mask)
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def biggest(mask):
    n, lab, st, _ = cv2.connectedComponentsWithStats(mask.astype(np.uint8), connectivity=4)
    i = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
    return lab == i


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True); ap.add_argument('--src', required=True)
    ap.add_argument('--width', type=float, default=340.0); ap.add_argument('--out'); ap.add_argument('--ts')
    a = ap.parse_args()
    out = a.out or f'public/assets/ui/hud-real/{a.name}'
    os.makedirs(out, exist_ok=True)
    rgb, alpha, *_ = bra.cut(a.src)
    crgb, ca, _ = bra.crop_to(rgb, alpha, pad=2)
    h, w = ca.shape
    s = a.width / w
    f = crgb.astype(np.int32)
    lum = (f[..., 0] * 299 + f[..., 1] * 587 + f[..., 2] * 114) // 1000
    opaque = ca > 0.5
    chroma = f.max(2) - f.min(2)
    ivory = opaque & (lum > 170) & (chroma < 60)
    ivory = cv2.morphologyEx(ivory.astype(np.uint8), cv2.MORPH_OPEN, np.ones((9, 9), np.uint8)).astype(bool)
    field = box(biggest(ivory))
    dark = opaque & (lum < 40)
    # window: dark component inside the field's upper two thirds
    dwin = dark.copy(); dwin[int(h * 0.66):, :] = False
    win = box(biggest(dwin))
    green = opaque & (f[..., 1] > f[..., 0] + 25) & (f[..., 1] > f[..., 2] - 10) & (lum > 50)
    gl = green.copy(); gl[:int(h * 0.66), :] = False
    gl = cv2.morphologyEx(gl.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8)).astype(bool)
    plq = box(biggest(gl))
    # the gold grade (hue 10-32, saturated) would stain the pale alabaster: keep the original ivory
    graded = bra.grade(crgb, ca).astype(np.float32)
    keep = cv2.GaussianBlur(biggest(ivory).astype(np.float32), (7, 7), 1.5)[..., None]
    mixed = (graded * (1 - keep) + crgb.astype(np.float32) * keep).clip(0, 255).astype(np.uint8)
    from PIL import Image
    im = Image.fromarray(np.dstack([mixed, (ca * 255).astype(np.uint8)]), 'RGBA')
    im = im.resize((round(im.width * s * bra.DPR), round(im.height * s * bra.DPR)), Image.LANCZOS)
    im.save(os.path.join(out, 'frame.webp'), 'WEBP', lossless=True, quality=100, method=6)
    size = im.size
    r = lambda b: {'x': round(b[0] * s, 2), 'y': round(b[1] * s, 2), 'w': round((b[2] - b[0]) * s, 2), 'h': round((b[3] - b[1]) * s, 2)}
    geo = {'w': round(w * s, 2), 'h': round(h * s, 2), 'field': r(field), 'window': r(win), 'plaque': r(plq), 'asset2x': list(size)}
    json.dump(geo, open(os.path.join(out, 'frame-geometry.json'), 'w'), indent=2)
    if a.ts:
        const = ''.join(p.capitalize() for p in a.name.split('-')).upper()
        open(a.ts, 'w').write(f'/**\n * GENERATED by scripts/hud-real/build-panel-assets.py ({a.name}) — do not edit by hand.\n'
                               ' * Frame image + boxes: `field` (alabaster), `window` (dark glass), `plaque` (emerald CTA). Design px; asset 2x.\n */\n'
                               f'export const {const}_FRAME = ' + json.dumps(geo, indent=2) + ' as const;\n')
    print(json.dumps(geo))


if __name__ == '__main__':
    main()
