import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const page = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:5173/game?poiDemo=1', { waitUntil: 'domcontentloaded', timeout: 30000 });
await page.waitForSelector('canvas', { timeout: 40000 }).catch(() => {});
await page.waitForTimeout(5000);
await page.evaluate(() => document.querySelector('[data-testid="hud-director-trigger"]')?.click());
await page.waitForTimeout(600);
const actions = await page.evaluate(() => [...document.querySelectorAll('[data-testid="director-panel"] [data-action-id]')].map((e) => e.dataset.actionId));
console.log('actions:', JSON.stringify(actions));
await page.evaluate(() => document.querySelector('[data-action-id="legacy"]')?.click());
await page.waitForTimeout(800);
const rel = await page.locator('[data-testid="hudreal-reliquary"]').count();
const stock = await page.locator('[data-testid="legacy-reliquary"]').count();
const cols = await page.locator('[data-testid^="hudreal-reliquary-col-"]').count();
const slots = await page.locator('[data-testid^="hudreal-reliquary-slot-"]').count();
console.log('hudreal:', rel, 'stock:', stock, 'cols:', cols, 'slots:', slots);
await page.screenshot({ path: 'test-results/reliquary-game.png' });
console.log('errors:', errors.length, errors.slice(0, 5));
await b.close();
