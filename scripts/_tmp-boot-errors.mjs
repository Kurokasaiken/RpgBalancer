import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
p.on('pageerror', (e) => console.log('[pageerror]', String(e).slice(0, 300)));
p.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 200)); });
await p.goto('http://localhost:5173/game', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(40000);
console.log('zanara count:', await p.evaluate(() => document.querySelectorAll('[data-poi-zanara]').length));
console.log('quest poi count:', await p.evaluate(() => document.querySelectorAll('[data-quest-poi-id]').length));
console.log('map ready:', await p.evaluate(() => !!document.querySelector('[data-map-ready]')));
await b.close();
