import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://localhost:5173/hud-compose?comp=cassetto&poi=poi-goblin&pcts=96,4&risk=3', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForSelector('[data-cassetto-column]', { timeout: 45000 });
await p.waitForTimeout(2000);
const info = await p.evaluate(() => {
  const R = (e) => e ? (({x,y,width,height,top,right,bottom,left})=>({x:Math.round(x*10)/10,y:Math.round(y*10)/10,w:Math.round(width*10)/10,h:Math.round(height*10)/10,top:Math.round(top*10)/10,right:Math.round(right*10)/10,bottom:Math.round(bottom*10)/10,left:Math.round(left*10)/10}))(e.getBoundingClientRect().toJSON()) : null;
  const q = (s) => document.querySelector(s);
  const out = {};
  out.cartouche = R(q('[data-cassetto-cartouche]'));
  out.title = R(q('[data-cassetto-cartouche] > div'));
  out.briefing = R(q('[data-cassetto-cartouche] p'));
  out.partyWell = R(q('[data-block="party-slots"]'));
  out.rack = R(q('[data-testid="resident-slot-rack"]'));
  out.seatCount = document.querySelectorAll('[data-slot-id],[data-testid^="slot-button"]').length;
  out.slotIds = Array.from(document.querySelectorAll('[data-hudreal-cassetto] [data-slot-id]')).map(e=>e.getAttribute('data-slot-id'));
  const seats = document.querySelectorAll('[data-hudreal-cassetto] [data-slot-id]');
  out.firstSeat = R(seats[0]); out.lastSeat = R(seats[seats.length-1]);
  out.bagWell = R(q('[data-block="bag-slots"]'));
  out.niches = Array.from(document.querySelectorAll('[data-testid^="bag-slot-"]')).map(R);
  out.journeyWell = R(q('[data-block="journey-strip"]'));
  out.journeyArt = R(q('[data-cassetto-journey-art]'));
  out.riskWell = R(q('[data-testid="cassetto-risk-well"]'));
  out.rewardWell = R(q('[data-testid="cassetto-reward-well"]'));
  out.cta = R(q('[data-testid="cassetto-confirm"]'));
  out.ctaImg = R(q('[data-testid="cassetto-confirm"] img'));
  out.ctaText = R(q('[data-testid="cassetto-confirm"] .confirm-text'));
  out.vignette = R(q('[data-cassetto-vignette-frame]'));
  out.column = R(q('[data-cassetto-column]'));
  return out;
});
console.log(JSON.stringify(info, null, 1));
await b.close();
