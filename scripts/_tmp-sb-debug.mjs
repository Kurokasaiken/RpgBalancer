import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('console', m => console.log('[console]', m.type(), m.text().slice(0,200)));
page.on('pageerror', e => console.log('[pageerror]', String(e).slice(0,300)));
const resp = await page.goto('http://localhost:5173/mockups/scroll-band-lab/', { waitUntil: 'load', timeout: 30000 });
console.log('status', resp.status());
await page.waitForTimeout(1500);
console.log('cand count:', await page.locator('.cand').count());
console.log('body html head:', (await page.locator('body').innerHTML()).slice(0, 400));
await browser.close();
