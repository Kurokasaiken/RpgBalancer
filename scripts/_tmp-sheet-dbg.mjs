import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1050, height: 900 } });
await p.goto('http://localhost:5173/hud-compose?comp=cassetto', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('[data-expedition-sheet]', { state: 'attached', timeout: 45000 });
await p.waitForTimeout(1500);
console.log('detent0:', await p.locator('[data-expedition-sheet]').getAttribute('data-detent'));
await p.locator('[data-testid="expedition-sheet-toggle"]').click().catch(e => console.log('toggle click fail:', String(e).slice(0,120)));
await p.waitForTimeout(1400);
console.log('detent1:', await p.locator('[data-expedition-sheet]').getAttribute('data-detent'));
await p.evaluate(() => document.querySelector('[data-cassetto-debug="select-first"]')?.click());
await p.waitForTimeout(5000);
const r = await p.locator('[data-testid="cassetto-risk-value"]').boundingBox();
console.log('risk box:', JSON.stringify(r));
await p.locator('[data-testid="cassetto-risk-value"]').scrollIntoViewIfNeeded().catch(()=>{});
await p.waitForTimeout(400);
const r2 = await p.locator('[data-testid="cassetto-risk-value"]').boundingBox();
console.log('risk box2:', JSON.stringify(r2));
await p.screenshot({ path: 'test-results/r357-phase8-witness/w1050-sheet-expanded.png' });
await b.close();
