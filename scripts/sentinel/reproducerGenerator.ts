/**
 * reproducerGenerator — emits a minimal self-contained Playwright spec that
 * reproduces a confirmed Sentinel finding (PLAN-078 T-004).
 *
 * The generated spec reaches the finding's state node through the harness
 * drivers and re-asserts the oracle invariant — the red test a `redfirst`
 * cycle needs. It is self-contained in the sense that it imports ONLY the
 * harness + oracles modules and needs only a dev server on `SENTINEL_URL`.
 */
import fs from 'node:fs';
import path from 'node:path';
import type { GatedFinding } from './oracles/index';
import type { ResolvedOwnership } from './componentResolver';

/** Returns the generated spec source for a confirmed finding. */
export function reproducerSource(f: GatedFinding, owner: ResolvedOwnership, runId: string): string {
  const title = `${f.oracle_id} @ ${f.state_node} (${f.perturbation_kind})`;
  return `/**
 * SENTINEL reproducer — ${title}
 * Generated by run ${runId}; fingerprint owner ${owner.component_id}.
 * Oracle: ${f.oracle_id} · signature: ${f.signature}
 * Evidence: ${JSON.stringify(f.evidence).slice(0, 300)}
 */
import { test, expect } from '@playwright/test';
import { DEFAULT_SENTINEL_CONFIG } from '../scripts/sentinel/sentinelConfig';
import { openGame, reachState, surfaceNode } from '../scripts/sentinel/gameSurfaceHarness';
import { auditState } from '../scripts/sentinel/oracles/index';

const CFG = DEFAULT_SENTINEL_CONFIG;
const OUT = 'test-results/sentinel-reproducers/${f.signature.slice(0, 16)}';

test('SENTINEL ${f.signature.slice(0, 12)} — ${title}', async () => {
  const ctx = await openGame({ baseURL: process.env.SENTINEL_URL ?? CFG.baseURL, outDir: OUT });
  try {
    const ok = await reachState(ctx, surfaceNode('${f.state_node}'));
    expect(ok, 'state ${f.state_node} must be reachable').toBe(true);
    const audit = await auditState(ctx, CFG, '${f.state_node}', '${f.perturbation_kind}');
    const hit = audit.findings.find((o) => o.signature === '${f.signature}');
    expect(hit, 'expected oracle ${f.oracle_id} to fire with signature ${f.signature}').toBeDefined();
  } finally {
    await ctx.browser.close();
  }
});
`;
}

/** Writes the reproducer spec under `outDir/reproducers/`; returns its path. */
export function writeReproducer(f: GatedFinding, owner: ResolvedOwnership, runId: string, outDir: string): string {
  const dir = path.join(outDir, 'reproducers');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${f.signature.slice(0, 16)}.spec.ts`);
  fs.writeFileSync(file, reproducerSource(f, owner, runId));
  return file;
}
