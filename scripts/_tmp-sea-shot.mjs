import { chromium } from 'playwright';
const page = await (await chromium.launch({ args: ['--enable-unsafe-swiftshader'] })).newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173/game', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__worldCam?.zoom > 0, null, { timeout: 240000 });
await page.waitForSelector('.game-boot-screen', { state: 'detached', timeout: 240000 }).catch(() => page.waitForTimeout(30000));
await page.waitForTimeout(1000);
await page.evaluate(() => window.__worldCamCtl.set({ zoom: 0.30 }));
await page.waitForTimeout(400);
await page.screenshot({ path: 'test-results/r331-zoom/sea-margin-z030.png' });
await page.evaluate(() => window.__worldCamCtl.set({ zoom: 0.18 }));
await page.waitForTimeout(400);
await page.screenshot({ path: 'test-results/r331-zoom/sea-margin-z018.png' });
console.log('shots saved');
process.exit(0);
