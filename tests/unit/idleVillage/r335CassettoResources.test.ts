/**
 * R-335 (2026-11-14) — «il mockup aveva il componente risorse in alto al suo
 * interno, perché scompare?» + «il cassetto dovrebbe essere più largo».
 *
 * The approved fork baseline (R-323 ruling "1 · Dentro la cornice",
 * `.mw/runs/20261110-cassetto-explore/column/fork-*.png`, PLAN-116 F1/F3) has
 * the village readout as TARGHETTE — dark-glass plaques inside the cleaned
 * header band of a 420px-wide recomposed column. The earlier mount of the
 * whole `HudRealResources` bar scaled into the well was the wrong shape: the
 * component is built for the top-right corner slot, and any scale that fits
 * the band makes it unreadable.
 *
 * Fix: `HudRealCassetto` renders the widened column art
 * (`scripts/hud-real/build-cassetto-column.py` → `column-1440/1280.webp` +
 * generated `cassettoColumnGeometry` zones) and mounts one plaque per
 * `resourceItems` entry in the cleaned band. Both production mounts
 * (`HudRealCassettoDetail` on /game, `HudRealCassettoHost` on the lab) feed it
 * the same `buildResourceReadoutItems(selectResourceOutlook(...))` pipeline.
 */
import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

const read = (p: string) => fs.readFileSync(path.resolve(__dirname, '../../../', p), 'utf8');

describe('R-335 — the cassetto owns the resources targhette inside its header band', () => {
  it('HudRealCassetto exposes resourceItems and renders one plaque per item (no corner bar)', () => {
    const src = read('src/ui/idleVillage/hudReal/HudRealCassetto.tsx');
    expect(src).toMatch(/resourceItems\?:\s*ResourceReadoutItem\[\]/);
    expect(src).toMatch(/data-cassetto-resources/);
    expect(src).toMatch(/data-cassetto-res=\{item\.id\}/);
    expect(src).not.toMatch(/HudRealResources|RESOURCES_BAR|resWellRef/);
  });

  it('the widened column art comes from the generated geometry, not the 639px frame', () => {
    const src = read('src/ui/idleVillage/hudReal/HudRealCassetto.tsx');
    expect(src).toMatch(/cassettoColumnSpec/);
    expect(src).toMatch(/CASSETTO_WIDE_BREAKPOINT/);
    const spec = read('src/ui/idleVillage/hudReal/layout/cassettoColumn.ts');
    expect(spec).toMatch(/column-1440\.webp/);
    expect(spec).toMatch(/column-1280\.webp/);
    const geo = read('src/ui/idleVillage/hudReal/cassettoColumnGeometry.ts');
    expect(geo).toMatch(/GENERATED by scripts\/hud-real\/build-cassetto-column\.py/);
    expect(geo).toMatch(/"resources"/);
    expect(geo).toMatch(/"confirm"/);
  });
});

describe('R-335 — both mounts feed the REAL readout (no lab fabrication)', () => {
  it('HudRealCassettoDetail (/game) builds items from selectResourceOutlook on the live store', () => {
    const src = read('src/ui/idleVillage/hudReal/HudRealCassettoDetail.tsx');
    expect(src).toMatch(/useMinimalGameplayWithIdleVillageConfig/);
    expect(src).toMatch(/buildResourceReadoutItems\(selectResourceOutlook\(state,\s*config\),\s*t\)/);
    expect(src).toMatch(/resourceItems=\{resourceItems\}/);
  });

  it('HudRealCassettoHost (lab) does the same through the same pipeline', () => {
    const src = read('src/ui/idleVillage/hudReal/HudRealCassettoHost.tsx');
    expect(src).toMatch(/useMinimalGameplayWithIdleVillageConfig/);
    expect(src).toMatch(/buildResourceReadoutItems\(selectResourceOutlook\(gpState,\s*gpConfig\),\s*t\)/);
    expect(src).toMatch(/resourceItems=\{resourceItems\}/);
  });
});

describe('R-335 — the lab column gives the drawer its ruled width', () => {
  it('hud-compose?comp=cassetto sizes the slot by viewport height (column art aspect)', () => {
    const src = read('src/pages/hud-compose.tsx');
    const cassettoBlock = src.match(/\{params\.get\('comp'\)\s*===\s*'cassetto'\s*&&\s*\(([\s\S]*?)\)\}/);
    expect(cassettoBlock).not.toBeNull();
    expect(cassettoBlock![1]).not.toMatch(/HudRealResources/);
    expect(cassettoBlock![1]).toMatch(/HudRealCassettoHost/);
    expect(cassettoBlock![1]).toMatch(/width:\s*'50vh'/);
  });
});
